#!/usr/bin/env python3
"""Build tests/bitmask_vectors.h: every AND-immediate encoding decoded by
llvm-objdump (an independent decoder) -> (sf, N, immr, imms, value)."""
import re, struct, subprocess, sys, tempfile, os

words, keys = [], []
for sf in (1, 0):
    for n in ((0, 1) if sf else (0,)):
        for immr in range(64 if sf else 32):
            for imms in range(64 if sf else 32):
                insn = (sf << 31) | (0b00100100 << 23) | (n << 22) | (immr << 16) | (imms << 10) | (1 << 5) | 0
                words.append(insn)
                keys.append((sf, n, immr, imms))
with tempfile.TemporaryDirectory() as d:
    raw = os.path.join(d, "w.bin")
    open(raw, "wb").write(b"".join(struct.pack("<I", w) for w in words))
    obj = os.path.join(d, "w.o")
    subprocess.check_call(["llvm-objcopy", "-I", "binary", "-O", "elf64-littleaarch64",
                           "--rename-section", ".data=.text,code", raw, obj])
    out = subprocess.check_output(["llvm-objdump", "-d", "--no-show-raw-insn", obj], text=True)
rows = []
lines = [l for l in out.splitlines() if re.match(r"\s+[0-9a-f]+:", l)]
assert len(lines) == len(words), (len(lines), len(words))
for key, line in zip(keys, lines):
    m = re.search(r"and\s+[wx]0, [wx]1, #(0x[0-9a-f]+|\d+)", line)
    if m:
        rows.append((*key, int(m.group(1), 0)))
with open(sys.argv[1], "w") as f:
    f.write("/* generated by tests/gen_bitmask.py from llvm-objdump output */\n")
    f.write("struct bm { int sf, n, immr, imms; uint64_t value; };\n")
    f.write("static const struct bm bitmask_vectors[] = {\n")
    for sf, n, immr, imms, v in rows:
        f.write(f"    {{ {sf}, {n}, {immr}, {imms}, {v:#x}ULL }},\n")
    f.write("};\n")
print(len(rows), "valid encodings")
